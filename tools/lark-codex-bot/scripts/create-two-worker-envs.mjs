#!/usr/bin/env node

import { existsSync, readFileSync } from "node:fs";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
const workspaceRoot = path.resolve(packageRoot, "../..");

const args = parseArgs(process.argv.slice(2));
const baseEnvPath = resolvePath(args.baseEnv || path.join(packageRoot, ".env.worker"));
const outputA = resolvePath(args.outputA || path.join(packageRoot, ".env.worker.bot-a"));
const outputB = resolvePath(args.outputB || path.join(packageRoot, ".env.worker.bot-b"));
const baseEnv = readDotEnv(baseEnvPath);

const hubBaseUrl = requiredBaseValue(baseEnv, "HUB_BASE_URL");
const hubWorkerToken = requiredBaseValue(baseEnv, "HUB_WORKER_TOKEN");
const codexWorkdir = baseEnv.CODEX_WORKDIR || workspaceRoot;
const codexBin = baseEnv.CODEX_BIN || "codex";
const codexSandbox = baseEnv.CODEX_SANDBOX || "workspace-write";
const codexModel = baseEnv.CODEX_MODEL || "";
const codexProfile = baseEnv.CODEX_PROFILE || "";
const codexHome = baseEnv.CODEX_HOME || "";
const larkBaseUrl = baseEnv.LARK_BASE_URL || "https://open.feishu.cn/open-apis";
const maxTurns = args.maxTurns || "4";
const triggerPrefix = args.triggerPrefix || "/debate";

const appA = readAppConfig("BOT_A", args.allowPlaceholder);
const appB = readAppConfig("BOT_B", args.allowPlaceholder);

await writeWorkerEnv(outputA, {
  app: appA,
  botId: args.botAId || "codex_bot_a",
  codexHome,
  codexModel,
  codexProfile,
  codexSandbox,
  codexWorkdir,
  codexBin,
  finalBotId: args.finalBotId || args.botAId || "codex_bot_a",
  hubBaseUrl,
  hubWorkerToken,
  larkBaseUrl,
  maxTurns,
  peerBotId: args.botBId || "codex_bot_b",
  promptPreamble: "你是 Codex Bot A，偏重工程落地、实现路径、成本和风险控制。讨论时先给可执行方案，再指出依赖、边界和验证方式。",
  sessionStore: path.join(packageRoot, ".sessions.bot-a.json"),
  triggerPrefix,
  visibleMention: args.botBMention || "@Codex-B",
  workerId: "codex-bot-a-worker",
});

await writeWorkerEnv(outputB, {
  app: appB,
  botId: args.botBId || "codex_bot_b",
  codexHome,
  codexModel,
  codexProfile,
  codexSandbox,
  codexWorkdir,
  codexBin,
  finalBotId: args.finalBotId || args.botAId || "codex_bot_a",
  hubBaseUrl,
  hubWorkerToken,
  larkBaseUrl,
  maxTurns,
  peerBotId: args.botAId || "codex_bot_a",
  promptPreamble: "你是 Codex Bot B，偏重反方审查、遗漏发现、替代方案和长期维护风险。讨论时主动挑战 Bot A 的假设，并给出更稳妥的改进建议。",
  sessionStore: path.join(packageRoot, ".sessions.bot-b.json"),
  triggerPrefix,
  visibleMention: args.botAMention || "@Codex-A",
  workerId: "codex-bot-b-worker",
});

console.log(`created ${path.relative(workspaceRoot, outputA)}`);
console.log(`created ${path.relative(workspaceRoot, outputB)}`);
if (args.allowPlaceholder) {
  console.log("warning: placeholder Feishu app credentials were written; replace them before running real two-bot replies.");
}

