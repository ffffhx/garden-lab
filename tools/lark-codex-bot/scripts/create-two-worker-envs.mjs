function readDotEnv(filePath) {
  if (!existsSync(filePath)) {
    throw new Error(`base env file not found: ${filePath}`);
  }

  const parsed = {};
  const text = readFileSync(filePath, "utf8");
  for (const line of text.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) {
      continue;
    }
    const match = /^([A-Za-z_][A-Za-z0-9_]*)=(.*)$/.exec(trimmed);
    if (!match) {
      continue;
    }
    parsed[match[1]] = unquote(match[2].trim());
  }
  return parsed;
}

function requiredBaseValue(env, key) {
  if (!env[key]) {
    throw new Error(`${key} is required in ${baseEnvPath}`);
  }
  return env[key];
}

function readAppConfig(prefix, allowPlaceholder) {
  const appId = process.env[`${prefix}_APP_ID`] || "";
  const appSecret = process.env[`${prefix}_APP_SECRET`] || "";
  if (appId && appSecret) {
    return { appId, appSecret };
  }
  if (allowPlaceholder) {
    return {
      appId: prefix === "BOT_A" ? "cli_bot_a" : "cli_bot_b",
      appSecret: prefix === "BOT_A" ? "replace-with-bot-a-secret" : "replace-with-bot-b-secret",
    };
  }

  throw new Error([
    `${prefix}_APP_ID and ${prefix}_APP_SECRET are required.`,
    "Example:",
    `  ${prefix}_APP_ID=cli_xxx ${prefix}_APP_SECRET=xxx pnpm lark:codex-setup-two-workers`,
    "Use --allow-placeholder only when you want local placeholder files.",
  ].join("\n"));
}

function parseArgs(argv) {
  const parsed = {
    allowPlaceholder: false,
    baseEnv: "",
    botAId: "",
    botAMention: "",
    botBId: "",
    botBMention: "",
    finalBotId: "",
    maxTurns: "",
    outputA: "",
    outputB: "",
    triggerPrefix: "",
  };

  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === "--") {
      continue;
    }
    if (arg === "--allow-placeholder") {
      parsed.allowPlaceholder = true;
      continue;
    }
    const option = arg.match(/^--([a-z0-9-]+)$/i)?.[1] || "";
    if (!option) {
      throw new Error(`unknown argument: ${arg}`);
    }
    const key = option.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase());
    if (!(key in parsed)) {
      throw new Error(`unknown option: ${arg}`);
    }
    parsed[key] = readArgValue(argv, ++index, arg);
  }

  return parsed;
}

function readArgValue(argv, index, option) {
  const value = argv[index];
  if (!value) {
    throw new Error(`${option} requires a value`);
  }
  return value;
}

function resolvePath(value) {
  if (path.isAbsolute(value)) {
    return value;
  }
  return path.resolve(workspaceRoot, value);
}

function unquote(value) {
  if (
    (value.startsWith('"') && value.endsWith('"')) ||
    (value.startsWith("'") && value.endsWith("'"))
  ) {
    return value.slice(1, -1);
  }
  return value;
}
